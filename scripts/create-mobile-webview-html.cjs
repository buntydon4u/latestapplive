const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const distDir = path.join(rootDir, 'dist');
const indexPath = path.join(distDir, 'index.html');
const outputPath = path.join(rootDir, 'mobile-webview-html.js');

const mimeTypes = {
  '.css': 'text/css',
  '.js': 'text/javascript',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.png': 'image/png',
  '.gif': 'image/gif',
  '.webp': 'image/webp',
  '.svg': 'image/svg+xml',
  '.woff': 'font/woff',
  '.woff2': 'font/woff2'
};

function readDistFile(publicPath) {
  const relativePath = publicPath.replace(/^\//, '');
  const filePath = path.resolve(distDir, relativePath);

  if (!filePath.startsWith(distDir)) {
    throw new Error(`Refusing to read outside dist: ${publicPath}`);
  }

  return {
    filePath,
    content: fs.readFileSync(filePath)
  };
}

function toDataUri(publicPath) {
  const { filePath, content } = readDistFile(publicPath);
  const mime = mimeTypes[path.extname(filePath).toLowerCase()] || 'application/octet-stream';
  return `data:${mime};base64,${content.toString('base64')}`;
}

function inlineCssAssets(css) {
  return css.replace(/url\((['"]?)(\/assets\/[^'")]+)\1\)/g, (_match, _quote, publicPath) => {
    return `url("${toDataUri(publicPath)}")`;
  });
}

if (!fs.existsSync(indexPath)) {
  throw new Error('dist/index.html not found. Run npm run build first.');
}

let html = fs.readFileSync(indexPath, 'utf8');

html = html.replace(/<link rel="stylesheet"[^>]*href="([^"]+)"[^>]*>/g, (_match, href) => {
  const { content } = readDistFile(href);
  const css = inlineCssAssets(content.toString('utf8'));
  return `<style>${css}</style>`;
});

html = html.replace(/<script type="module"[^>]*src="([^"]+)"[^>]*><\/script>/g, (_match, src) => {
  const { content } = readDistFile(src);
  return `<script type="module">${content.toString('utf8')}</script>`;
});

const output = [
  '// Generated by scripts/create-mobile-webview-html.cjs. Do not edit by hand.',
  `export const MOBILE_WEBVIEW_HTML = ${JSON.stringify(html)};`,
  ''
].join('\n');

fs.writeFileSync(outputPath, output);
console.log(`Generated ${path.relative(rootDir, outputPath)}`);
